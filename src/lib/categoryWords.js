/** 비목 → 검색어(공백으로 이은 글) */
export const categoryKeywords = (c) => {
  const name = String(c?.name || '')
  const hit = WORDS.filter(([re]) => re.test(name)).map(([, w]) => w)
  return [...hit, c?.group_name || ''].join(' ')
}

