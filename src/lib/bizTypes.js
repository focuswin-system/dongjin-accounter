/** Combobox 용 업태 옵션 */
export const bizTypeOptions = () => BIZ_TYPES.map(t => ({ value: t, label: t }))

/** Combobox 용 종목 옵션 — 업태를 고르면 그 업태의 것만, 안 골랐으면 전체를 보여준다.
 *  (업태를 아직 안 정한 채 종목부터 적는 사람도 있어서 막지 않는다) */
export function bizItemOptions(bizType) {
  const own = BIZ_ITEMS[bizType]
  if (own) return own.map(v => ({ value: v, label: v, sub: bizType }))
  return Object.entries(BIZ_ITEMS).flatMap(([type, items]) =>
    items.map(v => ({ value: v, label: v, sub: type })))
}
