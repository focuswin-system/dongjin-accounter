/** 검색용 — 블록에서 글자만 뽑는다. 표는 칸을 모두 이어 붙인다. */
export const blockText = (b) => {
  if (!b) return ''
  if (b.t === 'table') return (b.v || []).flat().join(' ')
  if (b.t === 'ul' || b.t === 'steps') return (b.v || []).join(' ')
  if (b.t === 'path') return b.v
  return String(b.v || '')
}
