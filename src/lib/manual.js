/**
 * 사용 설명서 — 앱 안에 사는 매뉴얼.
 *
 * ── 왜 FAQ 와 따로 두나 ──
 * FAQ(App.jsx FAQ_DATA)는 **막혔을 때** 보는 것이다: "입금을 어떻게 등록하나요?"
 * 매뉴얼은 **배울 때** 보는 것이다: 도입 교육, 인수인계, 새 담당자가 왔을 때.
 * 둘은 읽는 상황이 달라서 모양도 달라야 한다 — 하나는 검색으로 한 건을 집고,
 * 하나는 목차를 따라 처음부터 읽는다. 그래서 FAQ 는 서랍에, 매뉴얼은 전용 화면에 둔다.
 *
 * ── 화면 위치를 손으로 안 적는 이유 ──
 * `path: '잎 id'` 만 적으면 화면이 nav.js 의 NAV_PATH_OF 에서 뽑아 그린다.
 * 손으로 적어 두면 메뉴를 옮길 때마다 매뉴얼이 거짓말을 한다 — 이 프로젝트는
 * 브레드크럼 21개가 그렇게 어긋났던 적이 있다(f7a7f8f). 같은 실수를 되풀이하지 않는다.
 *
 * ⚠ **여기 적는 것은 지금 동작하는 것만.** 계획이나 곧 될 것을 적으면 매뉴얼이
 *   가장 나쁜 종류의 거짓말을 한다 — 사용자는 자기가 못 찾는 줄 알고 헤맨다.
 *
 * 블록 종류
 *   p     문단
 *   ul    목록
 *   steps 번호 붙은 절차 — '무엇을 누르면 무엇이 되는가'
 *   note  알아두기. tone: 'info'(기본) | 'warn'(잘못하면 장부가 틀어지는 것)
 *   path  화면 위치 + 바로 열기 버튼. 값은 **잎 id**
 *   table [[머리글…], [줄…], …]
 */

