/**
 * 거래를 **어떤 집계에 넣을 것인가** — 화면 쪽 단일 판정.
 *
 * 서버의 `lib/pnl.js` 와 짝을 이룬다. 서버는 SQL 로, 여기는 이미 받아 온 배열로 같은 판정을 한다.
 * (서버가 내려주는 `isPnl` 을 그대로 쓰되, 그 위에 얹는 예외를 여기 한 곳에 모은다.)
 *
 * ── 왜 필요한가 ──
 * 같은 판정을 화면 네 곳이 각자 손으로 적고 있었고, 조건이 조금씩 달랐다.
 *
 *   Docs.jsx      isPnl !== false || invoiceId
 *   Billing.jsx   invoiceId || noteId || isPnl !== false
 *   MiscPL.jsx    isPnl !== false && !invoiceId (+ 주문·급여 제외)
 *
 * 그래서 어음이 들어왔을 때 Billing 만 고쳐지고 Docs 는 그대로 남았다.
 * 규칙이 흩어지면 다음 예외에서 또 한쪽만 고쳐진다.
 *
 * ── 축은 하나다 ──
 * 처음에 '손익으로 세는가'와 '통장이 움직였는가'를 두 함수로 나누려 했는데,
 * 실제로 두 축이 갈리는 경우가 지금 코드에는 없다. 그래서 **이름을 하나로 둔다** —
 * 이름만 둘이고 식이 같으면 다음 사람이 "이미 갈려 있다"고 믿고 엉뚱한 쪽을 고른다.
 * (진짜로 갈려야 할 날이 오면 — 대출 실행처럼 손익은 아닌데 통장은 움직이는 것을
 *  입금내역에 세워야 할 때 — 그때 나누고 이 주석을 지운다.)
 */

/**
 * 매출·매입 집계에 넣을 거래인가.
 *
 * 서버 `lib/pnl.js` 의 `countableOnly()` 와 같은 규칙 —
 * "손익 계정이거나, 청구서 정산이거나, 어음 결제인 것".
 *
 * 청구서 정산의 상대 계정은 외상매출금(자산), 어음 결제는 받을어음·지급어음이라
 * 계정과목만 보면 전부 탈락한다. 그런데 이 앱은 미수금의 유일한 소스가 청구서다 —
 * 빼면 청구서를 쓰는 회사의 매출이 통째로 사라진다("2억이 들어왔는데 총 입금 0원").
 *
 * 걸러내려는 것은 **재무거래**다 — 대출 실행·원금 상환·예적금 납입·투자.
 * 그것들은 청구서도 어음도 없으므로 이 조건에 안 걸린다.
 */
export const isCountable = (t) =>
  t.isPnl !== false || !!t.invoiceId || !!t.noteId

/**
 * 손익이 아니라 걸러낸 거래 — 화면이 "무엇을 뺐는지" 말해줄 때 쓴다.
 *
 * 숫자가 틀린 건 아니지만, 화면이 뺀 것을 안 알려주면 사용자는 누락으로 읽는다.
 * ((주)포커스윈 실자료: 4월에 재고 매입 331,240원이 나갔는데 월별 현황엔 −0 으로 보였다.)
 */
export const notCountable = (t) => !isCountable(t)
