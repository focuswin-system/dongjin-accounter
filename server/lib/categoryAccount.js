/**
 * 비목 **이름**으로 계정과목 코드를 찾는다.
 *
 * 거래·청구서는 비목을 ID 가 아니라 **이름 문자열**로 들고 있다(transactions.category).
 * 그래서 조회 키가 이름이다 — 같은 이름이 수입·지출에 다 있을 수 있으므로 종류로 좁힌다.
 *
 * 청구서를 자동으로 발행하는 경로(정기지출·구매품의·마일스톤·분할)가 이 값을 안 넣으면,
 * **매입 청구서의 발행 전표가 차변 없이 선다** — 그 청구서는 일계표에 오르지 못한다.
 * 매출은 제품매출로 갈음되지만(lib/voucher.js) 매입은 갈음할 수 없다.
 *
 * @param db   테넌트 연결. 기본값을 두지 않는다 — 빠뜨리면 조용히 남의 회사를 읽는다.
 * @param kind 'issued'|'received' 또는 'income'|'expense'
 */
async function acctCodeByCategoryName(db, categoryName, kind) {
  if (!db) throw new Error('acctCodeByCategoryName: 테넌트 연결(db)이 필요합니다')
  const name = String(categoryName || '').trim()
  if (!name) return null
  const isIncome = kind === 'issued' || kind === 'income'
  const [[row]] = await db.execute(
    'SELECT account_code FROM categories WHERE name = ? AND id LIKE ? LIMIT 1',
    [name, isIncome ? 'INC-%' : 'EXP-%'])
  return row?.account_code || null
}

