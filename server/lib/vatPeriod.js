/* 부가세 과세기간·신고기한 — **한 곳에서만 정한다.**
 *
 * 부가세는 반기(1기 1~6월 / 2기 7~12월)를 다시 예정·확정으로 나눈다. 분기와 '기'가 1:1이 아니다.
 *   1~3월  = 1기 예정 (기한 4/25)      4~6월   = 1기 확정 (기한 7/25)
 *   7~9월  = 2기 예정 (기한 10/25)     10~12월 = 2기 확정 (기한 다음해 1/25)
 *
 * ⚠ 예전엔 이 표가 화면(screens/Docs.jsx)에만 있었다. 신고 자료 엑셀을 서버에서 만들면서
 *   같은 표가 두 벌이 될 뻔했는데, 신고 기한이 어긋나면 가산세로 이어진다 —
 *   화면과 엑셀이 다른 기한을 말하는 일은 있어선 안 된다.
 */
const QUARTERS = ['Q1', 'Q2', 'Q3', 'Q4']

const MONTHS = { Q1: ['01', '02', '03'], Q2: ['04', '05', '06'], Q3: ['07', '08', '09'], Q4: ['10', '11', '12'] }

function vatPeriodOf(quarter, year) {
  const y = Number(year)
  const M = {
    Q1: { from: `${y}-01-01`, to: `${y}-03-31`, label: '1기 예정신고', due: `${y}년 4월 25일` },
    Q2: { from: `${y}-04-01`, to: `${y}-06-30`, label: '1기 확정신고', due: `${y}년 7월 25일` },
    Q3: { from: `${y}-07-01`, to: `${y}-09-30`, label: '2기 예정신고', due: `${y}년 10월 25일` },
    Q4: { from: `${y}-10-01`, to: `${y}-12-31`, label: '2기 확정신고', due: `${y + 1}년 1월 25일` },
  }
  return M[quarter] || M.Q1
}

module.exports = { QUARTERS, MONTHS, vatPeriodOf }
